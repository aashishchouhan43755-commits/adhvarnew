#!/usr/bin/env bash
set -euo pipefail

# Run from the Flutter project even when invoked outside Netlify.
cd "$(dirname "${BASH_SOURCE[0]}")/.."

# Netlify's build image does not include Flutter. Keep the SDK outside the repo.
flutter_sdk_dir="$(mktemp -d)"
trap 'rm -rf "$flutter_sdk_dir"' EXIT
flutter_release_base="https://storage.googleapis.com/flutter_infra_release"
curl --fail --silent --show-error --location --retry 3 \
  "$flutter_release_base/releases/releases_linux.json" \
  --output "$flutter_sdk_dir/releases.json"

# Resolve the current stable Linux x64 SDK from Flutter's official manifest.
node - "$flutter_sdk_dir" <<'NODE'
const fs = require('node:fs');
const dir = process.argv[2];
const manifest = JSON.parse(fs.readFileSync(`${dir}/releases.json`, 'utf8'));
const release = manifest.releases.find((entry) =>
  entry.hash === manifest.current_release.stable &&
  entry.channel === 'stable' &&
  (!entry.dart_sdk_arch || entry.dart_sdk_arch === 'x64')
);
if (!release || !release.archive || !/^[a-f0-9]{64}$/i.test(release.sha256)) {
  throw new Error('No stable Linux x64 Flutter SDK with a checksum was found.');
}
fs.writeFileSync(`${dir}/archive-url`, `${manifest.base_url.replace(/\/$/, '')}/${release.archive}`);
fs.writeFileSync(`${dir}/sdk.sha256`, `${release.sha256}  ${dir}/sdk.tar.xz\n`);
fs.writeFileSync(`${dir}/release.json`, JSON.stringify(release));
NODE

curl --fail --silent --show-error --location --retry 3 \
  "$(cat "$flutter_sdk_dir/archive-url")" \
  --output "$flutter_sdk_dir/sdk.tar.xz"
sha256sum --check "$flutter_sdk_dir/sdk.sha256"
tar -xJf "$flutter_sdk_dir/sdk.tar.xz" -C "$flutter_sdk_dir"
export PATH="$flutter_sdk_dir/flutter/bin:$PATH"

flutter --no-version-check config --enable-web

# Initial tool bootstrapping regenerates the version cache using Git. Restore
# the verified release identity before Pub checks dependency SDK constraints.
# Preserve engine, Dart, and DevTools metadata generated by the installed SDK.
node - "$flutter_sdk_dir" <<'NODE'
const fs = require('node:fs');
const dir = process.argv[2];
const release = JSON.parse(fs.readFileSync(`${dir}/release.json`, 'utf8'));
const versionPath = `${dir}/flutter/bin/cache/flutter.version.json`;
const version = JSON.parse(fs.readFileSync(versionPath, 'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(release.version) || !release.hash || !release.release_date) {
  throw new Error('The stable release is missing valid Flutter version metadata.');
}
Object.assign(version, {
  frameworkVersion: release.version,
  flutterVersion: release.version,
  frameworkRevision: release.hash,
  frameworkCommitDate: release.release_date,
  channel: release.channel,
  repositoryUrl: 'https://github.com/flutter/flutter.git',
});
fs.writeFileSync(versionPath, JSON.stringify(version, null, 2));
fs.writeFileSync(`${dir}/flutter/version`, release.version);
NODE

flutter --no-version-check pub get
flutter --no-version-check build web --release
